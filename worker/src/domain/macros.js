const UNIT_GRAMS = {
  g: 1,
  ml: 1,
  tbsp: 15,
  tsp: 5,
  each: 60,
  kg: 1000,
  l: 1000,
};

export function lookupNutrition(name) {
  const n = String(name || "").toLowerCase().trim();
  if (NUTRITION_PER_100G[n]) return NUTRITION_PER_100G[n];
  const keys = Object.keys(NUTRITION_PER_100G).sort((a, b) => b.length - a.length);
  for (const key of keys) {
    if (n.includes(key)) return NUTRITION_PER_100G[key];
  }
  return null;
}

export function gramsForIngredient(quantity, unit) {
  if (quantity == null || !Number.isFinite(Number(quantity))) return null;
  const u = String(unit || "g").toLowerCase();
  const factor = UNIT_GRAMS[u] ?? (u === "kg" ? 1000 : u === "l" ? 1000 : null);
  if (factor == null) return null;
  return Number(quantity) * factor;
}

export function emptyMacros() {
  return { kcal: 0, protein: 0, carbs: 0, fat: 0, sugar: 0, estimated: true };
}

export function addMacros(a, b) {
  return {
    kcal: Math.round((a.kcal + b.kcal) * 10) / 10,
    protein: Math.round((a.protein + b.protein) * 10) / 10,
    carbs: Math.round((a.carbs + b.carbs) * 10) / 10,
    fat: Math.round((a.fat + b.fat) * 10) / 10,
    sugar: Math.round((a.sugar + b.sugar) * 10) / 10,
    estimated: Boolean(a.estimated || b.estimated),
  };
}

export function macrosForIngredient(ingredient) {
  const nut = lookupNutrition(ingredient.name);
  if (!nut) return { ...emptyMacros(), missing: true };
  const grams = gramsForIngredient(ingredient.quantity, ingredient.unit);
  if (grams == null) return { ...emptyMacros(), missing: true };
  const f = grams / 100;
  return {
    kcal: Math.round(nut.kcal * f * 10) / 10,
    protein: Math.round(nut.protein * f * 10) / 10,
    carbs: Math.round(nut.carbs * f * 10) / 10,
    fat: Math.round(nut.fat * f * 10) / 10,
    sugar: Math.round(nut.sugar * f * 10) / 10,
    estimated: true,
  };
}

export function macrosForIngredients(ingredients) {
  let total = emptyMacros();
  let known = 0;
  for (const ing of ingredients || []) {
    const m = macrosForIngredient(ing);
    if (!m.missing) {
      total = addMacros(total, m);
      known += 1;
    }
  }
  return { ...total, ingredients_matched: known, ingredients_total: (ingredients || []).length };
}

export function scaleMacros(macros, factor) {
  const f = Number(factor) || 1;
  return {
    kcal: Math.round(macros.kcal * f * 10) / 10,
    protein: Math.round(macros.protein * f * 10) / 10,
    carbs: Math.round(macros.carbs * f * 10) / 10,
    fat: Math.round(macros.fat * f * 10) / 10,
    sugar: Math.round(macros.sugar * f * 10) / 10,
    estimated: macros.estimated,
    ingredients_matched: macros.ingredients_matched,
    ingredients_total: macros.ingredients_total,
  };
}
